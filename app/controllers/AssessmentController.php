    public function store(): void
    {
        CSRF::check();
        $answers = $_POST['q'] ?? []; // รูปแบบ array: key => 1 (เห็นด้วย) หรือ 0 (ไม่เห็นด้วย)
        
        if (empty($answers)) {
            Session::flash('error', 'กรุณาตอบคำถามก่อนส่งแบบประเมิน');
            App::redirect('assessment/test');
            return;
        }

        $scores = ['R' => 0, 'I' => 0, 'A' => 0, 'S' => 0, 'E' => 0, 'C' => 0];
        
        foreach ($answers as $qId => $val) {
            if ($val == '1') {
                $type = substr($qId, 0, 1);
                if (isset($scores[$type])) {
                    $scores[$type]++;
                }
            }
        }

        // เรียงลำดับคะแนนจากมากไปน้อย เพื่อหา dominant trait
        arsort($scores);
        $topTypes = array_keys(array_slice($scores, 0, 3, true));
        $dominantTrait = implode('', $topTypes); // เช่น ISA, IRE, etc.
        
        $traitNames = [
            'R' => 'นักปฏิบัติ (Realistic)',
            'I' => 'นักวิเคราะห์ (Investigative)',
            'A' => 'นักสร้างสรรค์ (Artistic)',
            'S' => 'นักสังคมสงเคราะห์ (Social)',
            'E' => 'นักบริหาร (Enterprising)',
            'C' => 'นักจัดการ (Conventional)'
        ];

        $traitsDetails = [];
        foreach($topTypes as $t) {
            $traitsDetails[] = $traitNames[$t];
        }

        $resultData = [
            'scores' => $scores,
            'top_traits' => $traitsDetails,
            'holland_code' => $dominantTrait
        ];

        Database::insert(
            "INSERT INTO student_assessments (user_id, assessment_type, result_data, dominant_trait) VALUES (?, ?, ?, ?) ON DUPLICATE KEY UPDATE result_data = VALUES(result_data), dominant_trait = VALUES(dominant_trait)",
            [Auth::id(), 'riasec', json_encode($resultData, JSON_UNESCAPED_UNICODE), $dominantTrait]
        );

        Session::flash('success', 'ทำแบบประเมินเสร็จสมบูรณ์! ระบบได้ทำการวิเคราะห์ผลลัพธ์แล้ว');

        // Phase 5: Badge event trigger — riasec_taken
        try {
            BadgeService::onEvent(Auth::id(), 'riasec_taken');
            EXPService::award(Auth::id(), 'riasec_taken');
        } catch (\Throwable $e) {
            App::log("Badge check after riasec failed: " . $e->getMessage(), 'WARNING');
        }

        App::redirect('assessment');
    }
