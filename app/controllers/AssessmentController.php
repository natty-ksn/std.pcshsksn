    public function index(): void
    {
        $userId = Auth::id();
        $assessment = Database::fetch("SELECT * FROM student_assessments WHERE user_id = ? AND assessment_type = 'riasec' ORDER BY created_at DESC LIMIT 2", [$userId]);

        if (!$assessment) {
            // ยังไม่เคยประเมิน แนะนำให้ทำแบบทดสอบ
            $this->view('assessment.intro', []);
            return;
        }

        // แปลงผล JSON ให้แสดงในกราฟ
        $resultData = json_decode($assessment['result_data'], true);
        
        // Safety guard: Ensure keys exist
        $scores = $resultData['scores'] ?? [];
        $topTraits = $resultData['top_traits'] ?? [];
        
        $this->view('assessment.result', [
            'assessment' => $assessment,
            'scores' => $scores,
            'topTraits' => $topTraits
        ]);
    }

